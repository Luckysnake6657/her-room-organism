def main():
    rng = random.Random(123)
    rows = []
    for desc, e, s, a, i, l, presence, text in SCEN:
        b = model.Body()
        b.e, b.s, b.a, b.i, b.l = e, s, a, i, l
        af = affect.infer(b, text, presence)
        # A = 直接说出状态（也是她会说的话）；B = 推断后的模糊感受
        parts = []
        if e < 0.35:
            parts.append("有点累")
        if s > 0.6:
            parts.append("没睡够")
        if a > 0.55:
            parts.append("有点烦")
        if l > 0.6:
            parts.append("想找人说话")
        if i > 0.5:
            parts.append("不太舒服")
        a_line = "我现在" + ("、".join(parts) if parts else "还行") + "。"
        b_line = expression.render(af)
        pair = [("A", a_line), ("B", b_line)]
        rng.shuffle(pair)
        rows.append(dict(desc=desc, first=pair[0], second=pair[1]))
    md = ["# 哪句像她会说的话（20 题）", "",
          "每题给一个情境，下面两句是她可能说的话。**选更像她本人会说的那句**。", ""]
    for i, r in enumerate(rows, 1):
        md.append("%d. 情境：%s" % (i, r["desc"]))
        md.append("   1) %s" % r["first"][1])
        md.append("   2) %s" % r["second"][1])
    md.append("")
    md.append("回复：1:1 2:2 … 20:1（1=第一句，2=第二句）")
    open("evidence/p3/affect_blind.md", "w", encoding="utf-8").write("\n".join(md))
    json.dump(rows, open("evidence/p3/affect_blind.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    print("rows", len(rows))


if __name__ == "__main__":
    main()
